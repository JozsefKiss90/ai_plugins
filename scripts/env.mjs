#!/usr/bin/env node
// Exports the values in ./.env to your *user* environment so OpenCode's {env:VAR} substitution can see them.
//   Windows: `setx VAR value` (persistent user variables; open a new terminal afterwards)
//   macOS/Linux: writes ~/.config/opencode/env.sh and sources it from ~/.bashrc / ~/.zshrc / ~/.profile
// Usage: node scripts/env.mjs [--dry-run]
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { IS_WIN, log, c, readDotEnv, parseArgs, opencodeConfigDir } from "./lib.mjs";

export function applyEnv(env, { dry = false } = {}) {
  const keys = Object.keys(env);
  if (!keys.length) { log.warn("no values in .env (copy .env.example to .env and fill in what you have)"); return; }
  if (IS_WIN) {
    for (const k of keys) {
      log.info(`setx ${k} ${c.dim("••••")}`);
      if (!dry) {
        const r = spawnSync("setx", [k, env[k]], { encoding: "utf8" });
        if (r.status !== 0) log.err(`setx ${k} failed: ${r.stderr}`);
      }
      process.env[k] = env[k];
    }
    log.ok(`${keys.length} user variables set. Open a NEW terminal for them to take effect.`);
    return;
  }
  const file = path.join(opencodeConfigDir(), "env.sh");
  const body = ["# generated by OpenCode toolkit (scripts/env.mjs) — edit .env in the toolkit repo and re-run", ...keys.map((k) => `export ${k}=${shq(env[k])}`), ""].join("\n");
  log.info(`write ${file}`);
  if (!dry) { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, body, { mode: 0o600 }); }
  const line = `[ -f "${file}" ] && . "${file}"  # OpenCode toolkit`;
  for (const rc of [".bashrc", ".zshrc", ".profile"]) {
    const p = path.join(os.homedir(), rc);
    if (!fs.existsSync(p)) continue;
    if (fs.readFileSync(p, "utf8").includes("# OpenCode toolkit")) continue;
    log.info(`append source line to ~/${rc}`);
    if (!dry) fs.appendFileSync(p, `\n${line}\n`);
  }
  log.ok(`${keys.length} variables exported. Run: source "${file}"  (or open a new shell).`);
}
const shq = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"))) {
  const args = parseArgs(process.argv.slice(2));
  applyEnv(readDotEnv(), { dry: !!args["dry-run"] });
}
